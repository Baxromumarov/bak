// Command generate_prelude refreshes the compiler's embedded Bak prelude from
// the canonical standard-library sources.
package main

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

type preludeSource struct {
	constant string
	path     string
}

func main() {
	root, err := repositoryRoot()
	if err != nil {
		fail(err)
	}

	sources := []preludeSource{
		{constant: "hashmapPrelude", path: "src/std/collections/hashmap.bak"},
		{constant: "vecPrelude", path: "src/std/collections/vec.bak"},
		{constant: "resultPrelude", path: "src/std/result.bak"},
	}

	var generated strings.Builder
	generated.WriteString("package prelude\n\n// Code generated by scripts/generate_prelude; DO NOT EDIT.\n\n")
	for _, source := range sources {
		contents, readErr := os.ReadFile(filepath.Join(root, source.path))
		if readErr != nil {
			fail(fmt.Errorf("read %s: %w", source.path, readErr))
		}
		generated.WriteString("const " + source.constant + " = " + strconv.Quote(string(contents)) + "\n\n")
	}

	formatted, formatErr := format.Source([]byte(generated.String()))
	if formatErr != nil {
		fail(fmt.Errorf("format generated prelude: %w", formatErr))
	}

	output := filepath.Join(root, "pkg", "prelude", "embed_gen.go")
	if existing, readErr := os.ReadFile(output); readErr == nil && string(existing) == string(formatted) {
		return
	}
	if writeErr := os.WriteFile(output, formatted, 0o644); writeErr != nil {
		fail(fmt.Errorf("write %s: %w", output, writeErr))
	}
}

func repositoryRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", fmt.Errorf("get working directory: %w", err)
	}
	for {
		if _, statErr := os.Stat(filepath.Join(dir, "go.mod")); statErr == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("could not find repository root from %s", dir)
		}
		dir = parent
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "generate prelude:", err)
	os.Exit(1)
}
